package org.example;

public class Arithmetic_Expressions {
    public static void main(String[] args) {
        int result = 10/3;
        System.out.println(result);

        int x = 1;
        int y = ++x;
        System.out.println(x);
        System.out.println(y);

        int z = 10 + 3 * 2;
        System.out.println(z);

    }
}
